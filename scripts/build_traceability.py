#!/usr/bin/env python3
"""Build the requirements traceability matrix from requirements + test results.

Inputs : docs/requirements.yaml, reports/test_results.json (written by pytest)
Outputs: docs/traceability_matrix.md, and the matrix block inside README.md
         (between <!-- TRACE:START --> and <!-- TRACE:END -->)

Exit code is non-zero (a release gate) if any requirement has no test, any
traced test failed, or any test is not linked to a requirement.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
ICON = {"PASS": "✅ PASS", "FAIL": "❌ FAIL", "NOT COVERED": "⚠️ NOT COVERED", "SKIPPED": "⏭️ SKIPPED"}


def status_for(outcomes: list[str]) -> str:
    if not outcomes:
        return "NOT COVERED"
    if any(o == "failed" for o in outcomes):
        return "FAIL"
    if all(o == "skipped" for o in outcomes):
        return "SKIPPED"
    return "PASS"


def build(reqs: list[dict], results: list[dict]) -> tuple[str, str, list[str]]:
    by_req: dict[str, list[dict]] = {r["id"]: [] for r in reqs}
    problems = []
    for res in results:
        if not res["requirements"]:
            problems.append(f"test not linked to any requirement: {res['test']}")
        for rid in res["requirements"]:
            if rid not in by_req:
                problems.append(f"{res['test']} references unknown requirement {rid}")
            else:
                by_req[rid].append(res)

    full = ["| Req | Requirement | Risk | Test levels | Tests | Passed | Status |",
            "| --- | --- | :-: | --- | --: | --: | --- |"]
    short = ["| Req | Requirement | Risk | Tests | Status |", "| --- | --- | :-: | --: | --- |"]
    detail = []
    for r in reqs:
        tests = by_req[r["id"]]
        outcomes = [t["outcome"] for t in tests]
        st = status_for(outcomes)
        if st in ("FAIL", "NOT COVERED"):
            problems.append(f"{r['id']}: {st}")
        levels = ", ".join(sorted({t["level"] for t in tests})) or "-"
        n_pass = sum(o == "passed" for o in outcomes)
        full.append(f"| {r['id']} | {r['text']} | {r['risk']} | {levels} | {len(tests)} | {n_pass} | {ICON[st]} |")
        short.append(f"| {r['id']} | {r['text']} | {r['risk']} | {len(tests)} | {ICON[st]} |")
        detail.append(f"\n### {r['id']}: {r['text']}\n")
        for t in tests or [{"test": "(none)", "outcome": "-", "level": "-"}]:
            detail.append(f"- `{t['test']}` ({t['level']}): {t['outcome']}")
    return "\n".join(full) + "\n", "\n".join(short) + "\n", problems + [""] + detail


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--requirements", default=REPO / "docs/requirements.yaml")
    ap.add_argument("--results", default=REPO / "reports/test_results.json")
    ap.add_argument("--out", default=REPO / "docs/traceability_matrix.md")
    ap.add_argument("--readme", default=REPO / "README.md")
    a = ap.parse_args()

    reqs = yaml.safe_load(Path(a.requirements).read_text())
    data = json.loads(Path(a.results).read_text())
    full, short, rest = build(reqs, data["results"])
    split = rest.index("")
    problems, detail = rest[:split], rest[split + 1:]

    n_tests = len(data["results"])
    n_pass = sum(r["outcome"] == "passed" for r in data["results"])
    header = (f"# Requirements traceability matrix\n\n"
              f"Generated by `scripts/build_traceability.py` from `docs/requirements.yaml` and "
              f"`reports/test_results.json` ({data['generated']}). Do not edit by hand.\n\n"
              f"**{n_pass}/{n_tests} tests passed; {len(reqs)} requirements; "
              f"{'release gate PASSED' if not problems else 'release gate FAILED'}.**\n\n")
    gate = "\n## Gate problems\n\n" + "\n".join(f"- {p}" for p in problems) + "\n" if problems else ""
    Path(a.out).write_text(header + full + gate + "\n## Tests per requirement\n" + "\n".join(detail) + "\n")

    readme = Path(a.readme)
    if readme.exists():
        block = (f"<!-- TRACE:START -->\n_{n_pass}/{n_tests} tests passed · generated {data['generated']}_\n\n"
                 f"{short}<!-- TRACE:END -->")
        text = re.sub(r"<!-- TRACE:START -->.*?<!-- TRACE:END -->", block, readme.read_text(), flags=re.S)
        readme.write_text(text)

    print(full)
    if problems:
        print("RELEASE GATE FAILED:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    print(f"release gate PASSED: {n_pass}/{n_tests} tests, all {len(reqs)} requirements covered and passing")
    return 0


if __name__ == "__main__":
    sys.exit(main())
